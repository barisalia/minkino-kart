import {expect,test} from '@playwright/test';
// Kayıp bir düğme 120 sn beklemesin: Şef'te her eylem en çok 15 sn, her sayfa açılışı en çok 30 sn bekler.
test.use({actionTimeout:15_000,navigationTimeout:30_000});
test('Çocuk bahçeden kendi topladığı sebzeyi tezgahta doğrayabilir',async({page})=>{
  await page.setViewportSize({width:667,height:375});
  await page.goto('./sef/?test=1');await page.getByRole('button',{name:'Sesi kapat'}).tap();
  await page.locator('[data-tarif=salata]').tap();await page.locator('[data-istasyon=dolap]').tap();
  const gir=page.getByRole('button',{name:'Mutfak bahçesinden sebze topla'});
  await gir.tap();
  if(process.env.SEF_BAHCE_KARE)await page.screenshot({path:process.env.SEF_BAHCE_KARE});
  const domates=page.getByRole('button',{name:'Domates topla'});
  const r=(await domates.boundingBox())!;
  await page.mouse.move(r.x+r.width/2,r.y+r.height/2);await page.mouse.down();await page.mouse.move(r.x+40,r.y-42,{steps:8});await page.mouse.up();
  await expect(domates).toBeEnabled();
  await domates.dragTo(page.locator('.bostan-sepet'));
  await expect(domates).toBeHidden();
  await page.getByRole('button',{name:'Domates fidesini sula'}).tap();
  await expect(page.locator('[data-yer=domates]')).toHaveAttribute('data-sulandi','true');
  await page.getByRole('button',{name:'Marul topla'}).press('Enter');
  await page.getByRole('button',{name:'Seçtiğin sebzeyi sepete koy'}).press('Enter');
  await page.getByRole('button',{name:'Buzdolabına dön'}).tap();
  await expect(page.locator('.sepette-sebze')).toHaveCount(2);
  await page.reload();
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('minkino-sef-v1')!).siparisler.salata);
  expect((await state()).bahceden).toEqual(['domates','marul']);
  expect((await state()).sulanan).toEqual(['domates']);
  await page.locator('.sepette-sebze').first().tap();
  expect((await state()).bahceden).toEqual(['marul']);
  await gir.tap();await domates.dragTo(page.locator('.bostan-sepet'));
  await page.getByRole('button',{name:'Yan sebze sırasına git'}).tap();
  await page.getByRole('button',{name:'Salatalık topla'}).dragTo(page.locator('.bostan-sepet'));
  expect((await state()).bahceden).toEqual(['marul','domates','salatalik']);
  await page.getByRole('button',{name:'Bahçeden doğrama tahtasına git'}).tap();
  await expect(page.locator('[data-malzeme=domates]')).toBeVisible();
  await expect(page.locator('[data-malzeme=marul]')).toBeVisible();
});
